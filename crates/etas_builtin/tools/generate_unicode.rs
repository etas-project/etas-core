use std::{
    collections::{BTreeMap, BTreeSet},
    env,
    fmt::Write as _,
    fs,
    path::PathBuf,
};

#[derive(Debug)]
struct Decomposition {
    scalar: u32,
    compatibility: bool,
    offset: u32,
    len: u8,
}

#[derive(Debug)]
struct Mapping {
    scalar: u32,
    offset: u32,
    len: u8,
}

fn main() {
    let crate_dir = env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| env::current_dir().expect("current directory"));
    let source = crate_dir.join("src/text/unicode/data/source");
    let unicode_data =
        fs::read_to_string(source.join("UnicodeData.txt")).expect("read UnicodeData.txt");
    let exclusion_data = fs::read_to_string(source.join("CompositionExclusions.txt"))
        .expect("read CompositionExclusions.txt");
    let case_folding =
        fs::read_to_string(source.join("CaseFolding.txt")).expect("read CaseFolding.txt");
    let property_data = fs::read_to_string(source.join("PropList.txt")).expect("read PropList.txt");
    let derived_property_data = fs::read_to_string(source.join("DerivedCoreProperties.txt"))
        .expect("read DerivedCoreProperties.txt");
    let special_casing =
        fs::read_to_string(source.join("SpecialCasing.txt")).expect("read SpecialCasing.txt");

    let exclusions = exclusion_data
        .lines()
        .filter_map(data_field)
        .map(hex)
        .collect::<BTreeSet<_>>();
    let mut classes = Vec::new();
    let mut decompositions = Vec::new();
    let mut decomposition_scalars = Vec::new();
    let mut compositions = Vec::new();
    for line in unicode_data.lines().filter(|line| !line.is_empty()) {
        let fields = line.split(';').collect::<Vec<_>>();
        let scalar = hex(fields[0]);
        let class = fields[3].parse::<u8>().expect("canonical combining class");
        if class != 0 {
            classes.push((scalar, class));
        }
        let decomposition = fields[5].trim();
        if decomposition.is_empty() {
            continue;
        }
        let mut parts = decomposition.split_whitespace();
        let first = parts.next().expect("nonempty decomposition");
        let compatibility = first.starts_with('<');
        let mapping = if compatibility {
            parts.map(hex).collect::<Vec<_>>()
        } else {
            std::iter::once(hex(first))
                .chain(parts.map(hex))
                .collect::<Vec<_>>()
        };
        let offset = decomposition_scalars.len() as u32;
        decomposition_scalars.extend(mapping.iter().copied());
        decompositions.push(Decomposition {
            scalar,
            compatibility,
            offset,
            len: mapping.len().try_into().expect("decomposition length"),
        });
        if !compatibility && mapping.len() == 2 && !exclusions.contains(&scalar) {
            compositions.push((pair_key(mapping[0], mapping[1]), scalar));
        }
    }
    compositions.sort_unstable();

    let mut folds = Vec::new();
    let mut fold_scalars = Vec::new();
    for line in case_folding.lines() {
        let Some(line) = data_field(line) else {
            continue;
        };
        let fields = line.split(';').map(str::trim).collect::<Vec<_>>();
        if !matches!(fields[1], "C" | "F") {
            continue;
        }
        let mapping = fields[2].split_whitespace().map(hex).collect::<Vec<_>>();
        let offset = fold_scalars.len() as u32;
        fold_scalars.extend(mapping.iter().copied());
        folds.push(Mapping {
            scalar: hex(fields[0]),
            offset,
            len: mapping.len().try_into().expect("casefold length"),
        });
    }

    let whitespace = property_ranges(&property_data, "White_Space");
    let alphabetic = property_ranges(&derived_property_data, "Alphabetic");
    let cased = property_ranges(&derived_property_data, "Cased");
    let case_ignorable = property_ranges(&derived_property_data, "Case_Ignorable");
    let (numeric, control) = category_ranges(&unicode_data);
    let (lowercase, uppercase) = case_mappings(&unicode_data, &special_casing);

    let fingerprint = [
        unicode_data.as_bytes(),
        exclusion_data.as_bytes(),
        case_folding.as_bytes(),
        property_data.as_bytes(),
        derived_property_data.as_bytes(),
        special_casing.as_bytes(),
    ]
    .into_iter()
    .flatten()
    .fold(0xcbf29ce484222325_u64, |hash, byte| {
        (hash ^ u64::from(*byte)).wrapping_mul(0x100000001b3)
    });
    let mut output = String::new();
    writeln!(
        output,
        "// @generated by tools/generate_unicode.rs; do not edit."
    )
    .unwrap();
    writeln!(output, "pub const UNICODE_VERSION: &str = \"17.0.0\";").unwrap();
    writeln!(
        output,
        "pub const DATA_FINGERPRINT: u64 = 0x{fingerprint:016x};"
    )
    .unwrap();
    write_pairs(&mut output, "COMBINING_CLASSES", "(u32, u8)", &classes);
    writeln!(output, "pub static DECOMPOSITION_SCALARS: &[u32] = &[").unwrap();
    write_scalars(&mut output, &decomposition_scalars);
    writeln!(output, "];\n").unwrap();
    writeln!(
        output,
        "pub static DECOMPOSITIONS: &[DecompositionRecord] = &["
    )
    .unwrap();
    for value in decompositions {
        writeln!(
            output,
            "    DecompositionRecord {{ scalar: 0x{:x}, compatibility: {}, offset: {}, len: {} }},",
            value.scalar, value.compatibility, value.offset, value.len
        )
        .unwrap();
    }
    writeln!(output, "];\n").unwrap();
    write_pairs(&mut output, "COMPOSITIONS", "(u64, u32)", &compositions);
    writeln!(output, "pub static CASEFOLD_SCALARS: &[u32] = &[").unwrap();
    write_scalars(&mut output, &fold_scalars);
    writeln!(output, "];\n").unwrap();
    writeln!(output, "pub static CASEFOLDS: &[MappingRecord] = &[").unwrap();
    for value in folds {
        writeln!(
            output,
            "    MappingRecord {{ scalar: 0x{:x}, offset: {}, len: {} }},",
            value.scalar, value.offset, value.len
        )
        .unwrap();
    }
    writeln!(output, "];\n").unwrap();
    write_ranges(&mut output, "WHITE_SPACE_RANGES", &whitespace);
    write_ranges(&mut output, "ALPHABETIC_RANGES", &alphabetic);
    write_ranges(&mut output, "CASED_RANGES", &cased);
    write_ranges(&mut output, "CASE_IGNORABLE_RANGES", &case_ignorable);
    write_ranges(&mut output, "NUMERIC_RANGES", &numeric);
    write_ranges(&mut output, "CONTROL_RANGES", &control);
    write_mappings(&mut output, "LOWERCASE", &lowercase);
    write_mappings(&mut output, "UPPERCASE", &uppercase);
    if output.ends_with("\n\n") {
        output.pop();
    }
    fs::write(crate_dir.join("src/text/unicode/data/generated.rs"), output)
        .expect("write generated Unicode tables");
}

fn case_mappings(
    unicode_data: &str,
    special_casing: &str,
) -> (BTreeMap<u32, Vec<u32>>, BTreeMap<u32, Vec<u32>>) {
    let mut lowercase = BTreeMap::new();
    let mut uppercase = BTreeMap::new();
    for line in unicode_data.lines().filter(|line| !line.is_empty()) {
        let fields = line.split(';').collect::<Vec<_>>();
        let scalar = hex(fields[0]);
        if !fields[13].is_empty() {
            lowercase.insert(scalar, vec![hex(fields[13])]);
        }
        if !fields[12].is_empty() {
            uppercase.insert(scalar, vec![hex(fields[12])]);
        }
    }
    for line in special_casing.lines().filter_map(data_field) {
        let fields = line.split(';').map(str::trim).collect::<Vec<_>>();
        if !fields[4].is_empty() {
            continue;
        }
        let scalar = hex(fields[0]);
        lowercase.insert(scalar, fields[1].split_whitespace().map(hex).collect());
        uppercase.insert(scalar, fields[3].split_whitespace().map(hex).collect());
    }
    lowercase.retain(|scalar, mapping| mapping.as_slice() != [*scalar]);
    uppercase.retain(|scalar, mapping| mapping.as_slice() != [*scalar]);
    (lowercase, uppercase)
}

fn property_ranges(source: &str, property: &str) -> Vec<(u32, u32)> {
    let ranges = source.lines().filter_map(data_field).filter_map(|line| {
        let mut fields = line.split(';').map(str::trim);
        let range = fields.next()?;
        (fields.next()? == property).then(|| parse_range(range))
    });
    merge_ranges(ranges)
}

fn category_ranges(source: &str) -> (Vec<(u32, u32)>, Vec<(u32, u32)>) {
    let mut numeric = Vec::new();
    let mut control = Vec::new();
    let mut pending_range = None::<(u32, String)>;

    for line in source.lines().filter(|line| !line.is_empty()) {
        let fields = line.split(';').collect::<Vec<_>>();
        let scalar = hex(fields[0]);
        let name = fields[1];
        let category = fields[2];
        if name.ends_with(", First>") {
            pending_range = Some((scalar, category.to_owned()));
            continue;
        }
        let range = if name.ends_with(", Last>") {
            let (start, first_category) = pending_range.take().expect("Unicode range start");
            assert_eq!(first_category, category, "Unicode range category");
            (start, scalar)
        } else {
            (scalar, scalar)
        };
        if matches!(category, "Nd" | "Nl" | "No") {
            numeric.push(range);
        }
        if category == "Cc" {
            control.push(range);
        }
    }
    assert!(pending_range.is_none(), "unterminated Unicode range");
    (merge_ranges(numeric), merge_ranges(control))
}

fn parse_range(value: &str) -> (u32, u32) {
    let mut endpoints = value.split("..");
    let start = hex(endpoints.next().expect("range start"));
    let end = endpoints.next().map_or(start, hex);
    assert!(
        endpoints.next().is_none(),
        "Unicode range has two endpoints"
    );
    (start, end)
}

fn merge_ranges(ranges: impl IntoIterator<Item = (u32, u32)>) -> Vec<(u32, u32)> {
    let mut ranges = ranges.into_iter().collect::<Vec<_>>();
    ranges.sort_unstable();
    let mut merged = Vec::<(u32, u32)>::new();
    for (start, end) in ranges {
        if let Some((_, previous_end)) = merged.last_mut()
            && start <= previous_end.saturating_add(1)
        {
            *previous_end = (*previous_end).max(end);
        } else {
            merged.push((start, end));
        }
    }
    merged
}

fn data_field(line: &str) -> Option<&str> {
    let data = line.split('#').next()?.trim();
    (!data.is_empty()).then_some(data)
}

fn hex(value: &str) -> u32 {
    u32::from_str_radix(value.trim(), 16).expect("Unicode scalar")
}

fn pair_key(starter: u32, combining: u32) -> u64 {
    (u64::from(starter) << 21) | u64::from(combining)
}

fn write_scalars(output: &mut String, values: &[u32]) {
    for chunk in values.chunks(12) {
        output.push_str("    ");
        for (index, value) in chunk.iter().enumerate() {
            if index != 0 {
                output.push(' ');
            }
            write!(output, "0x{value:x},").unwrap();
        }
        output.push('\n');
    }
}

fn write_pairs<T: std::fmt::LowerHex + Copy, U: std::fmt::LowerHex + Copy>(
    output: &mut String,
    name: &str,
    ty: &str,
    values: &[(T, U)],
) {
    writeln!(output, "pub static {name}: &[{ty}] = &[").unwrap();
    for (left, right) in values {
        writeln!(output, "    (0x{left:x}, 0x{right:x}),").unwrap();
    }
    writeln!(output, "];\n").unwrap();
}

fn write_ranges(output: &mut String, name: &str, values: &[(u32, u32)]) {
    write_pairs(output, name, "(u32, u32)", values);
}

fn write_mappings(output: &mut String, name: &str, values: &BTreeMap<u32, Vec<u32>>) {
    let scalars = values
        .values()
        .flat_map(|mapping| mapping.iter().copied())
        .collect::<Vec<_>>();
    writeln!(output, "pub static {name}_SCALARS: &[u32] = &[").unwrap();
    write_scalars(output, &scalars);
    writeln!(output, "];\n").unwrap();
    writeln!(output, "pub static {name}_MAPPINGS: &[MappingRecord] = &[").unwrap();
    let mut offset = 0usize;
    for (scalar, mapping) in values {
        writeln!(
            output,
            "    MappingRecord {{ scalar: 0x{scalar:x}, offset: {offset}, len: {} }},",
            mapping.len()
        )
        .unwrap();
        offset += mapping.len();
    }
    writeln!(output, "];\n").unwrap();
}
