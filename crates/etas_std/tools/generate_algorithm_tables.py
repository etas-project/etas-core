#!/usr/bin/env python3
"""Generate exact decimal powers and Unicode 17.0.0 Quick_Check ranges.

Pass the official UCD 17 DerivedNormalizationProps.txt as the first argument.
https://www.unicode.org/Public/17.0.0/ucd/DerivedNormalizationProps.txt
"""
from pathlib import Path
import sys

library = Path(__file__).resolve().parents[1] / "library/std/text"
rows = []
for exponent in range(-348, 348):
    numerator = 10 ** max(exponent, 0)
    denominator = 10 ** max(-exponent, 0)
    binary = numerator.bit_length() - denominator.bit_length()
    if (numerator < denominator * 2**binary if binary >= 0 else numerator * 2**-binary < denominator):
        binary -= 1
    shift = binary - 127
    mantissa = numerator // (denominator * 2**shift) if shift >= 0 else (numerator * 2**-shift) // denominator
    rows.append(f"    DecimalPower {{ low= {mantissa % 2**64}, high= {mantissa // 2**64} }}, // 1e{exponent}")
(library / "float_tables.es").write_text(
    "module std.text;\n\n// @generated by tools/generate_algorithm_tables.py.\n"
    "// Exact rational powers of ten, normalized and rounded down to 128 bits.\n"
    "type DecimalPower = { private low: u128, private high: u128 };\n"
    "let DECIMAL_POWERS: Array<DecimalPower> = [\n" + "\n".join(rows) + "\n];\n"
)

data = Path(sys.argv[1]).read_text()
if "DerivedNormalizationProps-17.0.0.txt" not in data[:1000]:
    raise ValueError("Quick_Check input must be Unicode 17.0.0")
properties = {"NFC_QC": 1, "NFD_QC": 2, "NFKC_QC": 4, "NFKD_QC": 8}
points = {}
for line in data.splitlines():
    fields = [field.strip() for field in line.split("#", 1)[0].split(";")]
    if len(fields) < 3 or fields[1] not in properties or fields[2] not in ("N", "M"):
        continue
    bounds = [int(bound, 16) for bound in fields[0].split("..")]
    for code in range(bounds[0], bounds[-1] + 1):
        flags = points.setdefault(code, [0, 0])
        flags[fields[2] == "M"] += properties[fields[1]]
ranges = []
for code, flags in sorted(points.items()):
    if ranges and ranges[-1][1] + 1 == code and ranges[-1][2:] == flags:
        ranges[-1][1] = code
    else:
        ranges.append([code, code, *flags])
rows = [f"    QuickCheckRange {{ start= {start}, end= {end}, no= {no}, maybe= {maybe} }}," for start, end, no, maybe in ranges]
(library / "unicode/quick_check_data.es").write_text(
    "module std.text.unicode;\n\n// @generated by tools/generate_algorithm_tables.py.\n"
    "// Unicode 17.0.0 DerivedNormalizationProps.txt; Unicode License V3.\n"
    "// See normalization_data.es for the Unicode copyright and license notice.\n"
    "type QuickCheckRange = { start: u32, end: u32, no: u128, maybe: u128 };\n"
    "let QUICK_CHECK_RANGES: Array<QuickCheckRange> = [\n" + "\n".join(rows) + "\n];\n"
)
